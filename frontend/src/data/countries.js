export const getVisaBadgeClass = (colorName) => {
  const c = (colorName || '').toLowerCase()
  if (c.includes('green') || c.includes('free')) return 'badge-green'
  if (c.includes('blue') || c.includes('arrival')) return 'badge-blue'
  if (c.includes('yellow') || c.includes('e-visa') || c.includes('evisa')) return 'badge-yellow'
  return 'badge-red'
}

export const getMapFillColor = (colorName) => {
  const c = (colorName || '').toLowerCase()
  if (c.includes('green') || c.includes('free')) return '#22c55e'
  if (c.includes('blue') || c.includes('arrival')) return '#3b82f6'
  if (c.includes('yellow') || c.includes('e-visa') || c.includes('evisa')) return '#eab308'
  if (c.includes('red') || c.includes('required')) return '#ef4444'
  if (c.startsWith('#')) return colorName
  return '#d1d5db'
}
